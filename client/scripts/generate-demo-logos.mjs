const SIZE = 128;

function logoSvg([from, to, iconName]) {
  const icon = renderToStaticMarkup(
    createElement(icons[iconName], { size: 60, color: '#ffffff', strokeWidth: 2 }),
  );
  // A soft diagonal gradient, with the icon centered (logos are shown as circles)
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}">
    <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${from}"/><stop offset="1" stop-color="${to}"/>
    </linearGradient></defs>
    <rect width="${SIZE}" height="${SIZE}" fill="url(#g)"/>
    <g transform="translate(34 34)">${icon}</g>
  </svg>`;
}

const browser = await chromium.launch();
const page = await browser.newPage();
const logos = {};
for (const [key, design] of Object.entries(DESIGNS)) {
  logos[key] = await page.evaluate(async (svg) => {
    const img = new Image();
    img.src = 'data:image/svg+xml;base64,' + btoa(svg);
    await img.decode();
    const canvas = document.createElement('canvas');
    canvas.width = canvas.height = 128;
    canvas.getContext('2d').drawImage(img, 0, 0);
    return canvas.toDataURL('image/webp', 0.9);
  }, logoSvg(design));
}
await browser.close();

const out = new URL('../../server/src/demo/logos.ts', import.meta.url);
writeFileSync(
  out,
  `// Generated by client/scripts/generate-demo-logos.mjs: logos for the demo budget's made-up\n` +
    `// banks and businesses. Don't edit by hand; change the designs there and run it again.\n\n` +
    `export const DEMO_LOGOS = ${JSON.stringify(logos, null, 2)} as const;\n\n` +
    `export type DemoLogo = keyof typeof DEMO_LOGOS;\n`,
);
const bytes = Object.values(logos).reduce((s, l) => s + l.length, 0);
console.log(`Wrote ${Object.keys(logos).length} logos (${Math.round(bytes / 1024)} KB)`);
