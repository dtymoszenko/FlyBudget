const KNOWN = new Set(CURRENCY_CODES);

export const isCurrencyCode = (value: unknown): value is string =>
  typeof value === 'string' && KNOWN.has(value);

/** Decimals of a currency's amounts; 2 when it isn't known (a budget without a currency) */
export const minorUnits = (code: string | null | undefined): number =>
  code ? (MINOR_UNITS[code] ?? 2) : 2;

/** The currency an account is in: its own, or the budget's when it has none */
export const effectiveCurrency = (
  accountCurrency: string | null | undefined,
  budgetCurrency: string | null | undefined,
): string | null => accountCurrency ?? budgetCurrency ?? null;

/** Whether an account's amounts are in another currency than the budget's */
export const isForeign = (
  accountCurrency: string | null | undefined,
  budgetCurrency: string | null | undefined,
): boolean => !!accountCurrency && !!budgetCurrency && accountCurrency !== budgetCurrency;
